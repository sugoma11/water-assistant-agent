"""The selected candidate's tool text, repaired — and the third arm that makes (T136).

The one registered search selected candidate 4, and its whole difference from
candidate 1 is **one** rewritten tool description: the GR2L tool's, turned into a
root-agent system prompt with a role section, a three-tool routing table and a
restatement of the answer contract. Three things are wrong with it and each is a
byte-level defect rather than a matter of taste:

* It names ``agent_tool_predict_green_roof_water_balance_tool`` — the *registered
  prompt* name, which is what ``component_name`` hands the reflection model
  (``findings.md`` § Optimizer internals) — five times, and the real callable
  ``predict_green_roof_water_balance_tool`` never. Its routing table therefore
  points at a tool no toolset resolves.
* It legislates for the *other* tools from inside one tool's declaration.
* It restates the root instruction's answer contract, where a disagreement
  between the two copies would be invisible — and the copies already disagree,
  since it adds a ``final_text`` key and an ``"error"`` status the contract does
  not have.

**Surgical means measured, not tidied.** That rewrite is the entire difference
between candidate 1 and the winner and it moved trajectory 0.76 → 0.87, so the
routing content may be what is doing the work and a repair that deletes it
discards the gain. The four routing discriminations survive verbatim in
``gr2l_repaired.md``, recast from a table that tells the agent which tool to pick
into one that says when *this* tool applies; what is deleted is the role framing,
the contract restatement and the two examples about other tools.

**Both sides are committed, so the diff is readable without the registry.**
``eval/repair/gr2l_selected.md`` is the winner's text byte for byte as registered,
``gr2l_repaired.md`` is the repair, and ``gr2l.diff`` is the unified diff between
them, regenerated from the two rather than typed. :func:`verify` holds all three
to each other and to the registry, which is the same anti-drift check
``just candidates-check`` runs on the seed.

**It is a third arm and never the optimized one.** §7's registration defines the
optimized arm as *whatever candidate the one registered search selects*,
explicitly not a hand-picked one. A repaired candidate is therefore a separate
arm with its own registration section (``repair_measurement`` in
``eval/preregistration.json``) and its own measured numbers — and those numbers
need a budget decision that is T134's, not this module's.
"""

from __future__ import annotations

import difflib
from collections.abc import Mapping
from pathlib import Path

import structlog

from harness.candidates import CANDIDATE_COMPONENTS, prompt_name, read_candidate
from water_assistant_agent.assistant.toolset import GREEN_ROOF_TOOL

logger = structlog.get_logger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[1]

REPAIR_DIR = REPO_ROOT / "eval" / "repair"

SELECTED_FILE = REPAIR_DIR / "gr2l_selected.md"
"""The selected candidate's GR2L text, byte for byte as the search registered it."""

REPAIRED_FILE = REPAIR_DIR / "gr2l_repaired.md"
"""The repair. Neither file ends in a newline: both are prompt payloads, not prose."""

DIFF_FILE = REPAIR_DIR / "gr2l.diff"
"""The unified diff between the two, regenerated by :func:`repair_diff`."""

REPAIRED_COMPONENT = GREEN_ROOF_TOOL
"""The one component the repair touches. Every other component is the winner's."""


class RepairDriftError(RuntimeError):
    """The committed repair no longer matches what it is a repair *of*.

    Raised when the selected text on disk is not the registered candidate's, or
    when the committed diff is not the diff between the two committed files. Both
    are the same failure wearing different clothes: a repair whose starting point
    cannot be reproduced is a rewrite, and a rewrite is not what §7 licenses a
    third arm for.
    """


def selected_text() -> str:
    """The winner's GR2L description, as committed."""
    return SELECTED_FILE.read_text(encoding="utf-8")


def repaired_text() -> str:
    """The repaired GR2L description, as committed."""
    return REPAIRED_FILE.read_text(encoding="utf-8")


def repair_diff() -> str:
    """The unified diff from the selected text to the repaired one.

    Computed from the two committed files rather than read from
    :data:`DIFF_FILE`, so that the committed diff can be checked against it
    instead of being trusted.

    Line-based rather than byte-based (``lineterm=""`` over ``splitlines()``):
    neither payload ends in a newline, and a keepends diff renders the last
    removed and the first added line as one run-together line. The bytes are in
    the two files; this is the record of what moved between them.
    """
    lines = difflib.unified_diff(
        selected_text().splitlines(),
        repaired_text().splitlines(),
        fromfile=f"a/{SELECTED_FILE.relative_to(REPO_ROOT)}",
        tofile=f"b/{REPAIRED_FILE.relative_to(REPO_ROOT)}",
        lineterm="",
    )
    return "\n".join(lines) + "\n"


def repaired_texts(optimized_versions: Mapping[str, int]) -> dict[str, str]:
    """The selected candidate's seven texts with the GR2L description repaired.

    Args:
        optimized_versions: The versions the search recorded for the arm it
            selected, read from ``eval/optimized_candidate.json``.

    Returns:
        Component → text. Six components are read back from the registry at the
        optimized arm's own versions, so the repaired arm differs from the arm it
        repairs in exactly one string.

    Raises:
        RepairDriftError: the registered GR2L text is not the committed selected
            one — see :func:`verify`, which this calls.
    """
    verify(optimized_versions)
    texts = {
        component: read_candidate(component, optimized_versions[component])
        for component in CANDIDATE_COMPONENTS
    }
    texts[REPAIRED_COMPONENT] = repaired_text()
    return texts


def verify(optimized_versions: Mapping[str, int]) -> None:
    """Hold the committed repair to the candidate it repairs, and to its own diff.

    Raises:
        RepairDriftError: the registered text moved out from under the committed
            copy, or the committed diff is not the diff between the two files.
    """
    registered = read_candidate(
        REPAIRED_COMPONENT, optimized_versions[REPAIRED_COMPONENT]
    )
    if registered != selected_text():
        raise RepairDriftError(
            f"{SELECTED_FILE.relative_to(REPO_ROOT)} is not the text registered at "
            f"{prompt_name(REPAIRED_COMPONENT)} "
            f"v{optimized_versions[REPAIRED_COMPONENT]} "
            f"({len(selected_text())} chars committed, {len(registered)} registered). "
            "The repair's starting point is the selected candidate or it is nothing."
        )
    if DIFF_FILE.read_text(encoding="utf-8") != repair_diff():
        raise RepairDriftError(
            f"{DIFF_FILE.relative_to(REPO_ROOT)} is not the diff between "
            f"{SELECTED_FILE.name} and {REPAIRED_FILE.name}. Regenerate it with "
            "`just repair-diff` rather than editing it: the diff is the record of "
            "what was changed, and a hand-edited one records something else."
        )
    logger.info(
        "The committed repair matches the selected candidate",
        component=REPAIRED_COMPONENT,
        version=optimized_versions[REPAIRED_COMPONENT],
    )


def write_diff() -> Path:
    """Regenerate :data:`DIFF_FILE` from the two committed texts."""
    DIFF_FILE.parent.mkdir(parents=True, exist_ok=True)
    DIFF_FILE.write_text(repair_diff(), encoding="utf-8")
    return DIFF_FILE


